function toolkitFactOfDay(date) {
  const d = date || new Date();
  const start = new Date(d.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((d - start) / 86400000);
  // Offset by year so the same date doesn't repeat the same fact every year
  const i = (dayOfYear + d.getFullYear() * 7) % TOOLKIT_FACTS.length;
  return { index: i, category: TOOLKIT_FACTS[i][0], text: TOOLKIT_FACTS[i][1] };
}
